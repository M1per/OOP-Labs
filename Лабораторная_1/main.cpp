#include <iostream>

/**
 * @brief Заполняет статический массив целыми числами.
 *
 * Функция получает массив из 10 элементов по ссылке
 * и заполняет его значениями, введёнными пользователем.
 *
 * @param arr Массив из 10 целых чисел.
 */
void fillArray(int (&arr)[10]) // arr — ссылка на массив из 10 целых чисел
{
    std::cout << "Введите 10 целых чисел: ";

    for (int i = 0; i < 10; ++i) // Проходим по всем 10 элементам
    {
        std::cin >> arr[i]; // Вводим значение в текущий элемент
    }
}

/**
 * @brief Выводит элементы массива на экран.
 *
 * Функция получает массив из 10 элементов по ссылке
 * и выводит все его элементы с помощью range-based for.
 *
 * @param arr Массив из 10 целых чисел.
 */
void printArray(int (&arr)[10]) // arr — ссылка на массив из 10 целых чисел
{
    for (auto x : arr) // x автоматически получает тип элемента массива
    {
        std::cout << x << " "; // Выводим текущий элемент
    }

    std::cout << std::endl;
}

/**
 * @brief Меняет местами два элемента массива.
 *
 * Функция получает массив и два индекса,
 * после чего меняет значения элементов с этими индексами местами.
 *
 * @param arr Массив из 10 целых чисел.
 * @param index1 Индекс первого элемента.
 * @param index2 Индекс второго элемента.
 */
void swapElements(int (&arr)[10], int& index1, int& index2)
{
    int temp = arr[index1]; // Сохраняем первый элемент во временную переменную
    arr[index1] = arr[index2]; // На место первого элемента ставим второй
    arr[index2] = temp; // На место второго ставим сохранённое первое значение
}

/**
 * @brief Умножает каждый элемент массива на два.
 *
 * Функция проходит по массиву с помощью range-based for
 * и изменяет каждый элемент через неконстантную ссылку.
 *
 * @param arr Массив из 10 целых чисел.
 */
void multiplyByTwo(int (&arr)[10]) // arr — ссылка на массив из 10 целых чисел
{
    for (int& x : arr) // x — ссылка на настоящий элемент массива
    {
        x *= 2; // Умножаем текущий элемент на два
    }
}

int main()
{
    int arr[10]{}; // Статический массив из 10 целых чисел

    fillArray(arr); // Заполняем массив

    printArray(arr); // Выводим исходный массив

    int index1 = 0; // Индекс первого элемента
    int index2 = 9; // Индекс последнего элемента

    swapElements(arr, index1, index2); // Меняем первый и последний элементы

    printArray(arr); // Выводим массив после обмена

    multiplyByTwo(arr); // Умножаем все элементы массива на два

    printArray(arr); // Выводим массив после умножения

    return 0;
}