#include <iostream>

/**
 * @brief Обрабатывает динамический массив.
 *
 * Функция находит первый отрицательный элемент.
 * Если отрицательный элемент найден, создаёт новый массив,
 * копирует в него элементы до первого отрицательного,
 * освобождает старую память и изменяет указатель arr.
 *
 * @param arr Ссылка на указатель на динамический массив.
 * @param size Размер динамического массива.
 */
void process(int*& arr, int size) // arr — ссылка на указатель, чтобы изменить сам указатель
{
    // Пока функция будет реализована на следующем этапе.
}

int main()
{
    int size;

    std::cout << "Введите размер массива: ";
    std::cin >> size;

    int* arr = new int[size]{}; // Выделяем и обнуляем динамический массив

    std::cout << "Введите " << size << " целых чисел: ";

    for (int i = 0; i < size; ++i) // Заполняем массив
    {
        std::cin >> arr[i];
    }

    process(arr, size); // Передаём указатель по ссылке

    std::cout << "Результат: ";

    for (int i = 0; i < size; ++i)
    {
        std::cout << arr[i] << " ";
    }

    std::cout << std::endl;

    delete[] arr; // Освобождаем динамическую память
    arr = nullptr; // Обнуляем указатель после освобождения памяти

    if (arr == nullptr) // Проверяем, что указатель действительно обнулён
    {
        std::cout << "Указатель обнулён, обращаться к памяти нельзя." << std::endl;
    }

    return 0;
}